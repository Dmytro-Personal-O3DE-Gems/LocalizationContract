
#pragma once

#include <LocalizationContract/LocalizationContractTypeIds.h>

#include <AzCore/EBus/EBus.h>
#include <AzCore/Interface/Interface.h>
#include <AzCore/RTTI/RTTI.h>
#include <AzCore/std/optional.h>
#include <AzCore/std/string/string.h>

namespace LocalizationContract
{
    //! Contract for requesting localized text by key.
    //!
    //! This gem only declares the contract. The implementation lives in another gem
    //! (e.g. LocalizationGem). Only one implementation should be active at a time.
    //!
    //! Implementations MUST provide both access paths:
    //!   1. register in LocalizationContractInterface (AZ::Interface<LocalizationContractRequests>::Register);
    //!   2. connect to LocalizationContractRequestBus (LocalizationContractRequestBus::Handler::BusConnect).
    //! The system component generated by the Default Gem template already does both.
    //!
    //! Consumers may use either path:
    //!   - LocalizationContractInterface::Get() returns nullptr when no implementation is active;
    //!   - LocalizationContractRequestBus::BroadcastResult leaves the result untouched when no
    //!     implementation is connected, so initialize the result to "not found" before the call.
    //! In both cases the consumer falls back to its own default text.
    //!
    //! Language changes are announced on LocalizationContractNotificationBus
    //! (LocalizationContractNotificationBus.h).
    class LocalizationContractRequests
    {
    public:
        AZ_RTTI(LocalizationContractRequests, LocalizationContractRequestsTypeId);
        virtual ~LocalizationContractRequests() = default;

        //! Returns the text for the given key in the current language,
        //! or an empty optional if there is no text for this key.
        //! The implementation may apply its own fallback (e.g. a default language) before
        //! reporting "no text"; the consumer then uses its own default text.
        //! Returns a copy on purpose: the implementation may rebuild its tables when the language changes.
        virtual AZStd::optional<AZStd::string> GetLocalizedString(const AZStd::string& key) const = 0;

        //! Returns the code of the current language, e.g. "en", "es", "uk" (ISO 639-1 / BCP 47 style).
        //! An empty string means the language is unknown.
        virtual AZStd::string GetCurrentLanguage() const = 0;
    };

    class LocalizationContractBusTraits
        : public AZ::EBusTraits
    {
    public:
        //////////////////////////////////////////////////////////////////////////
        // EBusTraits overrides
        static constexpr AZ::EBusHandlerPolicy HandlerPolicy = AZ::EBusHandlerPolicy::Single;
        static constexpr AZ::EBusAddressPolicy AddressPolicy = AZ::EBusAddressPolicy::Single;
        //////////////////////////////////////////////////////////////////////////
    };

    using LocalizationContractRequestBus = AZ::EBus<LocalizationContractRequests, LocalizationContractBusTraits>;
    using LocalizationContractInterface = AZ::Interface<LocalizationContractRequests>;

} // namespace LocalizationContract
